import React from 'react';
import { videoIntro } from '../data/portfolioData';
import { Play, Sparkles, Volume2, Clock, Video } from 'lucide-react';

export default function VideoIntro({ onOpenVideo }) {
  // Extract YouTube video ID if present for automatic high-res thumbnail
  const getYouTubeThumbnail = (url) => {
    if (!url) return null;
    const match = url.match(/(?:embed\/|v=|youtu\.be\/|\/v\/)([^?&"/]+)/);
    return match ? `https://img.youtube.com/vi/${match[1]}/maxresdefault.jpg` : null;
  };

  const thumbnailUrl = getYouTubeThumbnail(videoIntro.embedUrl);
  return (
    <section id="video-intro" className="py-20 md:py-28 bg-neutral-50/80 border-y border-neutral-200">
      <div className="max-w-7xl mx-auto px-6 sm:px-8">
        {/* Section Header */}
        <div className="flex flex-col md:flex-row md:items-end justify-between mb-12 gap-6">
          <div>
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-brand-50 border border-brand-200 mb-3">
              <Sparkles className="w-3.5 h-3.5 text-brand" />
              <span className="text-xs font-mono font-semibold uppercase tracking-wider text-brand-700">
                {videoIntro.badge}
              </span>
            </div>
            <h2 className="font-display font-bold text-3xl sm:text-4xl md:text-5xl text-ink-950 tracking-tight">
              {videoIntro.title}
              <span className="text-brand">.</span>
            </h2>
          </div>
          <p className="text-sm sm:text-base text-ink-600 max-w-md font-normal leading-relaxed">
            {videoIntro.subtitle}
          </p>
        </div>

        {/* Video Feature Card */}
        <div className="relative rounded-3xl overflow-hidden bg-ink-950 text-white shadow-2xl border border-neutral-800">
          {/* Ambient Orange Glow behind thumbnail */}
          <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-96 h-96 bg-brand/20 rounded-full blur-3xl pointer-events-none"></div>

          <div className="relative grid grid-cols-1 lg:grid-cols-12 items-center">
            {/* Left: Video Thumbnail & Play Trigger */}
            <div className="lg:col-span-7 p-6 sm:p-10">
              <div 
                onClick={onOpenVideo}
                className="group relative aspect-video rounded-2xl overflow-hidden bg-gradient-to-br from-neutral-900 via-neutral-950 to-black border border-neutral-700/80 cursor-pointer shadow-elevated flex items-center justify-center transition-all duration-300 hover:border-brand/60"
                role="button"
                tabIndex={0}
                aria-label="Play Husain Shakruwala introduction video"
                onKeyDown={(e) => {
                  if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    onOpenVideo();
                  }
                }}
              >
                {/* Background Video Thumbnail or Subtle Grid Pattern */}
                {thumbnailUrl ? (
                  <>
                    <img 
                      src={thumbnailUrl} 
                      alt={videoIntro.title} 
                      className="absolute inset-0 w-full h-full object-cover transition-transform duration-500 group-hover:scale-105"
                      onError={(e) => {
                        // Fallback to hqdefault if maxresdefault is not generated by YouTube
                        if (e.target.src.includes('maxresdefault')) {
                          e.target.src = e.target.src.replace('maxresdefault', 'hqdefault');
                        }
                      }}
                    />
                    <div className="absolute inset-0 bg-ink-950/40 group-hover:bg-ink-950/20 transition-colors duration-300" />
                  </>
                ) : (
                  <div 
                    className="absolute inset-0 opacity-15"
                    style={{
                      backgroundImage: `linear-gradient(#FB7319 1px, transparent 1px), linear-gradient(90deg, #FB7319 1px, transparent 1px)`,
                      backgroundSize: '40px 40px'
                    }}
                  />
                )}

                {/* Simulated Audio Waveform Graphic */}
                <div className="absolute bottom-6 left-6 right-6 flex items-center justify-between pointer-events-none opacity-40 group-hover:opacity-80 transition-opacity">
                  <div className="flex items-center gap-1.5 h-6">
                    {[40, 65, 30, 85, 55, 95, 45, 75, 35, 60, 90, 50, 70, 30, 80].map((height, i) => (
                      <span 
                        key={i} 
                        className="w-1 bg-brand rounded-full transition-all duration-300 group-hover:bg-white"
                        style={{ height: `${height}%` }}
                      />
                    ))}
                  </div>
                  <span className="font-mono text-xs text-neutral-400 group-hover:text-white flex items-center gap-1.5">
                    <Volume2 className="w-3.5 h-3.5 text-brand" />
                    <span>AUDIO / VIDEO INTRO</span>
                  </span>
                </div>

                {/* Central Play Button */}
                <div className="relative z-10 flex flex-col items-center gap-3">
                  <div className="relative flex items-center justify-center w-20 h-20 sm:w-24 sm:h-24 rounded-full bg-brand text-white shadow-glow-orange group-hover:scale-110 group-hover:bg-brand-400 transition-all duration-300">
                    <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-brand opacity-40"></span>
                    <Play className="w-8 h-8 sm:w-10 sm:h-10 fill-white translate-x-1" />
                  </div>
                  <span className="font-display font-semibold text-xs tracking-widest uppercase text-white/90 group-hover:text-brand transition-colors">
                    Click to Play Preview
                  </span>
                </div>

                {/* Duration Badge */}
                <div className="absolute top-4 right-4 z-10 flex items-center gap-1.5 px-3 py-1 rounded-full bg-black/75 backdrop-blur-md border border-neutral-700 text-xs font-mono text-neutral-200">
                  <Clock className="w-3 h-3 text-brand" />
                  <span>{videoIntro.duration}</span>
                </div>

                {/* Top Left Status Badge */}
                <div className="absolute top-4 left-4 z-10 flex items-center gap-2 px-3 py-1 rounded-full bg-black/75 backdrop-blur-md border border-neutral-700 text-xs font-mono text-neutral-200">
                  <span className="w-2 h-2 rounded-full bg-brand animate-pulse"></span>
                  <span>HD 1080P</span>
                </div>
              </div>
            </div>

            {/* Right: Personal Perspective & Easy Config Callout */}
            <div className="lg:col-span-5 p-6 sm:p-10 lg:pl-0 flex flex-col justify-between">
              <div>
                <span className="text-xs font-mono uppercase tracking-widest text-brand font-semibold mb-3 block">
                  PERSONAL STATEMENT
                </span>
                <blockquote className="font-display text-lg sm:text-xl font-medium text-neutral-100 leading-snug mb-6 italic">
                  {videoIntro.placeholderQuote}
                </blockquote>
                
                <div className="flex items-center gap-3 pt-4 border-t border-neutral-800">
                  <div className="w-10 h-10 rounded-full bg-neutral-800 border border-neutral-700 flex items-center justify-center text-brand font-display font-bold text-sm">
                    HS
                  </div>
                  <div>
                    <h4 className="font-display font-bold text-sm text-white">
                      {videoIntro.speakerName}
                    </h4>
                    <p className="text-xs text-neutral-400">
                      {videoIntro.speakerTitle}
                    </p>
                  </div>
                </div>
              </div>

              {/* Beginner-friendly instructions card */}
              <div className="mt-8 p-4 rounded-xl bg-neutral-900/90 border border-neutral-800 text-neutral-300">
                <div className="flex items-center gap-2 text-xs font-semibold text-white mb-1.5">
                  <Video className="w-4 h-4 text-brand" />
                  <span>How to add your real video:</span>
                </div>
                <p className="text-xs text-neutral-400 leading-relaxed">
                  Open <code className="text-brand font-mono">src/data/portfolioData.js</code> and paste your YouTube, Loom, or Vimeo link into <code className="text-neutral-200 font-mono">embedUrl</code>. It updates instantly with no coding needed!
                </p>
                <div className="mt-3">
                  <button
                    onClick={onOpenVideo}
                    className="w-full py-2.5 px-4 rounded-lg bg-neutral-800 hover:bg-neutral-700 text-xs font-semibold text-white transition-colors flex items-center justify-center gap-2 border border-neutral-700"
                  >
                    <Play className="w-3.5 h-3.5 text-brand" />
                    <span>Open Interactive Video Player</span>
                  </button>
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
